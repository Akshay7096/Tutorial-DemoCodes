public class Employee {

    private String Name;
    private String Dept;

    Employee(String Name, String Dept) {
        this.Name = Name;
        this.Dept = Dept;
    }

    void setterName () {
        this.Name = Name;
    }
    void setterDept () {
        this.Name = Name;
    }

    String getterName () {
        return Name;
    }

    String getterDept () {
        return Dept;
    }
}

